//! Host test harness for `lc_walkthrough_test`.
//!
//! Matches the DV sequence (`chip_sw_lc_walkthrough_vseq.sv`):
//! 1. Device starts in `RAW` (`count = 0`). CPU is disabled.
//! 2. Host connects to `JtagTap::LcTap`, verifies `RAW` state, and triggers JTAG transition
//!    to `TEST_UNLOCKED0` (`count = 1`) using `RND_CNST_RAW_UNLOCK_TOKEN`.
//! 3. Host removes `PINMUX_TAP_LC` strap and resets chip into `TEST_UNLOCKED0`.
//! 4. Device boots into `TEST_UNLOCKED0` (`count = 1`), programs & locks `SECRET0` (`kOtpUnlockToken`,
//!    `kOtpExitToken`), issues software reset via `rstmgr`, reboots into `TEST_UNLOCKED0` (`secret0_locked = true`),
//!    initiates LC transition to `DEV` (`kDestState`) using `kLcExitToken`, and logs
//!    `"Waiting for LC transition done and reboot."`.
//! 5. Host resets chip into `DEV` (`count = 2`).
//! 6. Device boots into `DEV` (`count = 2`), programs & locks `SECRET2` (`kOtpRmaToken`),
//!    issues software reset via `rstmgr`, reboots into `DEV` (`secret2_locked = true`),
//!    initiates LC transition to `RMA` using `kLcRmaToken`, and logs
//!    `"Waiting for LC RMA transition done and reboot."`.
//! 7. Host resets chip into `RMA` (`count = 3`).
//! 8. Device boots into `RMA` (`count = 3`), verifies state and count, and reports `PASS!`.

use std::path::PathBuf;
use std::time::Duration;

use anyhow::{Context, Result, ensure};
use clap::Parser;
use opentitanlib::app::UartRx;
use opentitanlib::dif::lc_ctrl::{DifLcCtrlState, DifLcCtrlToken, LcCtrlReg};
use opentitanlib::io::jtag::JtagTap;
use opentitanlib::test_utils::init::InitializeTest;
use opentitanlib::test_utils::lc_transition;
use opentitanlib::uart::console::UartConsole;

// Generated by the `lc_raw_unlock_token` Bazel rule from `//rules/lc.bzl`.
mod lc_raw_unlock_token;

#[derive(Debug, Parser)]
struct Opts {
    #[command(flatten)]
    init: InitializeTest,

    /// Run `lc_walkthrough_testunlocks_test` (walkthrough TestUnlocked0..7 via TestLocked0..6).
    #[arg(long, default_value_t = false)]
    pub testunlocks: bool,

    /// Firmware image to reload via bootstrap after RMA flash wipe (`lc_walkthrough_test`).
    #[arg(long)]
    pub firmware: Option<PathBuf>,

    #[arg(long, value_parser = humantime::parse_duration, default_value = "60s")]
    pub timeout: Duration,
}

const TEST_UNLOCK_TOKEN_PREIMAGE: [u32; 4] = [0x03020100, 0x07060504, 0x0b0a0908, 0x0f0e0d0c];

fn main() -> Result<()> {
    let opts = Opts::parse();
    opts.init.init_logging();

    let transport = opts.init.init_target()?;
    let uart = transport.uart("console")?;

    // Phase 1: Device starts in RAW (count = 0). CPU is disabled.
    log::info!("Phase 1: Connecting to LC TAP in RAW state...");
    transport.pin_strapping("PINMUX_TAP_LC")?.apply()?;
    transport.reset(UartRx::Clear)?;

    let mut jtag = opts
        .init
        .jtag_params
        .create(&transport)?
        .connect(JtagTap::LcTap)
        .context("Failed to connect to LC TAP in RAW state")?;

    let state = jtag.read_lc_ctrl_reg(&LcCtrlReg::LcState)?;
    ensure!(
        state == DifLcCtrlState::Raw.redundant_encoding(),
        "Expected initial LC state RAW, got 0x{:x}",
        state
    );
    let cnt = jtag.read_lc_ctrl_reg(&LcCtrlReg::LcTransitionCnt)?;
    ensure!(cnt == 0, "Expected initial LC transition count 0, got {}", cnt);

    let token = DifLcCtrlToken::from(lc_raw_unlock_token::RND_CNST_RAW_UNLOCK_TOKEN.to_le_bytes());
    let token_words = token.into_register_values();

    log::info!("Triggering JTAG transition from RAW to TEST_UNLOCKED0...");
    uart.clear_rx_buffer()?;
    lc_transition::trigger_lc_transition(
        &transport,
        jtag,
        DifLcCtrlState::TestUnlocked0,
        Some(token_words),
        /*use_external_clk=*/ true,
        /*reset_tap_straps=*/ Some(JtagTap::LcTap),
    )
    .context("Failed JTAG transition to TEST_UNLOCKED0")?;

    if opts.testunlocks {
        let locked_states = [
            DifLcCtrlState::TestLocked0,
            DifLcCtrlState::TestLocked1,
            DifLcCtrlState::TestLocked2,
            DifLcCtrlState::TestLocked3,
            DifLcCtrlState::TestLocked4,
            DifLcCtrlState::TestLocked5,
            DifLcCtrlState::TestLocked6,
        ];
        let unlocked_states = [
            DifLcCtrlState::TestUnlocked1,
            DifLcCtrlState::TestUnlocked2,
            DifLcCtrlState::TestUnlocked3,
            DifLcCtrlState::TestUnlocked4,
            DifLcCtrlState::TestUnlocked5,
            DifLcCtrlState::TestUnlocked6,
            DifLcCtrlState::TestUnlocked7,
        ];

        for i in 0..7 {
            log::info!(
                "Waiting for SW to request transition to {:?}...",
                locked_states[i]
            );
            _ = UartConsole::wait_for(
                &*uart,
                r"Waiting for LC transtition \d+ done and reboot\.",
                opts.timeout,
            )
            .with_context(|| {
                format!(
                    "Failed waiting for SW to initiate transition to {:?}",
                    locked_states[i]
                )
            })?;

            log::info!("Resetting into {:?}...", locked_states[i]);
            uart.clear_rx_buffer()?;
            transport.reset(UartRx::Clear)?;

            let mut jtag = opts
                .init
                .jtag_params
                .create(&transport)?
                .connect(JtagTap::LcTap)
                .with_context(|| format!("Failed to connect to LC TAP in {:?}", locked_states[i]))?;

            let state = jtag.read_lc_ctrl_reg(&LcCtrlReg::LcState)?;
            ensure!(
                state == locked_states[i].redundant_encoding(),
                "Expected LC state {:?}, got 0x{:x}",
                locked_states[i],
                state
            );
            let exp_cnt = (2 * i + 2) as u32;
            let cnt = jtag.read_lc_ctrl_reg(&LcCtrlReg::LcTransitionCnt)?;
            ensure!(
                cnt == exp_cnt,
                "Expected LC transition count {}, got {}",
                exp_cnt,
                cnt
            );

            log::info!(
                "Triggering JTAG transition from {:?} to {:?}...",
                locked_states[i],
                unlocked_states[i]
            );
            uart.clear_rx_buffer()?;
            lc_transition::trigger_lc_transition(
                &transport,
                jtag,
                unlocked_states[i],
                Some(TEST_UNLOCK_TOKEN_PREIMAGE),
                /*use_external_clk=*/ true,
                /*reset_tap_straps=*/ Some(JtagTap::LcTap),
            )
            .with_context(|| {
                format!(
                    "Failed JTAG transition from {:?} to {:?}",
                    locked_states[i], unlocked_states[i]
                )
            })?;
        }

        transport.pin_strapping("PINMUX_TAP_LC")?.remove()?;

        log::info!("Waiting for test PASS in TEST_UNLOCKED7...");
        _ = UartConsole::wait_for(&*uart, r"PASS!.*", opts.timeout)
            .context("Failed waiting for test PASS in TEST_UNLOCKED7")?;

        log::info!("LC walkthrough testunlocks test completed successfully.");
        return Ok(());
    }

    transport.pin_strapping("PINMUX_TAP_LC")?.remove()?;

    // Phase 2: Device boots in TEST_UNLOCKED0 (reset by trigger_lc_transition),
    // locks SECRET0, SW-resets, and requests DEV transition.
    log::info!("Phase 2: Waiting for SW to lock SECRET0 and initiate transition to DEV...");
    _ = UartConsole::wait_for(
        &*uart,
        r"Waiting for LC transition done and reboot\.",
        opts.timeout,
    )
    .context("Failed waiting for SW to initiate transition from TEST_UNLOCKED0 to DEV")?;

    // Phase 3: Reset chip into DEV state (count = 2).
    log::info!("Phase 3: Resetting chip into DEV state...");
    uart.clear_rx_buffer()?;
    transport.reset(UartRx::Clear)?;

    // Device boots in DEV, locks SECRET2, SW-resets, and requests RMA transition.
    log::info!("Phase 4: Waiting for SW to lock SECRET2 and initiate transition to RMA...");
    _ = UartConsole::wait_for(
        &*uart,
        r"Waiting for LC RMA transition done and reboot\.",
        opts.timeout,
    )
    .context("Failed waiting for SW to initiate transition from DEV to RMA")?;

    // Phase 5: Reset into RMA state (count = 3). Since RMA transition wipes flash,
    // re-bootstrap the firmware image over SPI and wait for SW test PASS.
    log::info!("Phase 5: Bootstrapping firmware into RMA state after flash wipe...");
    uart.clear_rx_buffer()?;
    let firmware = opts
        .firmware
        .as_ref()
        .context("--firmware is required for lc_walkthrough_test")?;
    opts.init
        .bootstrap
        .load(&transport, firmware)
        .context("Failed to bootstrap firmware after RMA transition")?;

    _ = UartConsole::wait_for(&*uart, r"PASS!.*", opts.timeout)
        .context("Failed waiting for test PASS in RMA state")?;

    log::info!("LC walkthrough test completed successfully.");
    Ok(())
}
